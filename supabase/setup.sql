-- EcoScan schema for a new Supabase project.
-- Safe to run again: tables and policies are created or updated without
-- deleting existing rows.

create table if not exists public.scans (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now()
);

alter table public.scans
    add column if not exists waste_name text,
    add column if not exists category text,
    add column if not exists disposal_method text,
    add column if not exists co2_saved numeric not null default 0,
    add column if not exists created_at timestamptz not null default now();

alter table public.scans enable row level security;
grant select, insert on public.scans to anon, authenticated;

drop policy if exists "Anyone can read EcoScan scans" on public.scans;
create policy "Anyone can read EcoScan scans"
    on public.scans for select to anon, authenticated
    using (true);

drop policy if exists "Anyone can save EcoScan scans" on public.scans;
create policy "Anyone can save EcoScan scans"
    on public.scans for insert to anon, authenticated
    with check (
        waste_name is not null
        and char_length(trim(waste_name)) between 1 and 120
        and category is not null
        and char_length(trim(category)) between 1 and 80
        and disposal_method is not null
        and char_length(trim(disposal_method)) between 1 and 160
        and co2_saved >= 0
    );

create table if not exists public.impact_actions (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now()
);

alter table public.impact_actions
    add column if not exists waste_type text,
    add column if not exists category text,
    add column if not exists action text,
    add column if not exists latitude double precision,
    add column if not exists longitude double precision,
    add column if not exists location_name text,
    add column if not exists impact_value numeric not null default 0,
    add column if not exists created_at timestamptz not null default now();

alter table public.impact_actions enable row level security;
grant select, insert on public.impact_actions to anon, authenticated;

drop policy if exists "Anyone can read EcoScan impact actions"
    on public.impact_actions;
create policy "Anyone can read EcoScan impact actions"
    on public.impact_actions for select to anon, authenticated
    using (true);

drop policy if exists "Anyone can add EcoScan impact actions"
    on public.impact_actions;
create policy "Anyone can add EcoScan impact actions"
    on public.impact_actions for insert to anon, authenticated
    with check (
        waste_type is not null
        and char_length(trim(waste_type)) between 1 and 120
        and category is not null
        and char_length(trim(category)) between 1 and 80
        and action is not null
        and char_length(trim(action)) between 1 and 160
        and latitude between -90 and 90
        and longitude between -180 and 180
        and impact_value >= 0
    );

create table if not exists public.scan_feedback (
    id bigint generated by default as identity primary key,
    original_label text not null,
    corrected_label text not null,
    original_category text not null,
    corrected_category text not null check (
        corrected_category in (
            'Organic',
            'Anorganic',
            'Residue',
            'B3 / Hazardous',
            'Reusable'
        )
    ),
    estimated_mass_grams integer not null check (
        estimated_mass_grams between 1 and 100000
    ),
    model_confidence real not null check (
        model_confidence between 0 and 1
    ),
    model_predictions jsonb not null default '[]'::jsonb,
    created_at timestamptz not null default now()
);

alter table public.scan_feedback
    add column if not exists original_label text,
    add column if not exists corrected_label text,
    add column if not exists original_category text,
    add column if not exists corrected_category text,
    add column if not exists estimated_mass_grams integer,
    add column if not exists model_confidence real,
    add column if not exists model_predictions jsonb not null default '[]'::jsonb,
    add column if not exists created_at timestamptz not null default now();

alter table public.scan_feedback enable row level security;
grant insert on public.scan_feedback to anon, authenticated;

do $$
declare
    id_sequence text;
begin
    id_sequence := pg_get_serial_sequence('public.scan_feedback', 'id');
    if id_sequence is not null then
        execute format(
            'grant usage, select on sequence %s to anon, authenticated',
            id_sequence
        );
    end if;
end
$$;

drop policy if exists "Allow scan correction submissions"
    on public.scan_feedback;
create policy "Allow scan correction submissions"
    on public.scan_feedback for insert to anon, authenticated
    with check (
        corrected_category in (
            'Organic',
            'Anorganic',
            'Residue',
            'B3 / Hazardous',
            'Reusable'
        )
        and estimated_mass_grams between 1 and 100000
        and model_confidence between 0 and 1
    );

create table if not exists public.ecoscan_reviews (
    id bigint generated by default as identity primary key,
    display_name text,
    rating smallint not null check (rating between 1 and 5),
    review_text text not null check (
        char_length(trim(review_text)) between 1 and 1200
    ),
    created_at timestamptz not null default now(),
    constraint ecoscan_reviews_display_name_length check (
        display_name is null
        or char_length(trim(display_name)) between 1 and 60
    )
);

alter table public.ecoscan_reviews
    drop constraint if exists ecoscan_reviews_review_text_check;
alter table public.ecoscan_reviews
    add constraint ecoscan_reviews_review_text_check
    check (char_length(trim(review_text)) between 1 and 1200);
alter table public.ecoscan_reviews enable row level security;
grant select, insert on public.ecoscan_reviews to anon, authenticated;

do $$
declare
    id_sequence text;
begin
    id_sequence := pg_get_serial_sequence('public.ecoscan_reviews', 'id');
    if id_sequence is not null then
        execute format(
            'grant usage, select on sequence %s to anon, authenticated',
            id_sequence
        );
    end if;
end
$$;

drop policy if exists "Anyone can read EcoScan reviews"
    on public.ecoscan_reviews;
create policy "Anyone can read EcoScan reviews"
    on public.ecoscan_reviews for select to anon, authenticated
    using (true);

drop policy if exists "Anyone can publish EcoScan reviews"
    on public.ecoscan_reviews;
create policy "Anyone can publish EcoScan reviews"
    on public.ecoscan_reviews for insert to anon, authenticated
    with check (
        rating between 1 and 5
        and char_length(trim(review_text)) between 1 and 1200
        and (
            display_name is null
            or char_length(trim(display_name)) between 1 and 60
        )
    );

drop policy if exists "Only EcoScan owner can delete reviews"
    on public.ecoscan_reviews;
revoke delete on public.ecoscan_reviews from anon, authenticated;

do $$
begin
    if exists (
        select 1
        from pg_publication
        where pubname = 'supabase_realtime'
    ) and not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'ecoscan_reviews'
    ) then
        alter publication supabase_realtime
            add table public.ecoscan_reviews;
    end if;
end
$$;

do $$
declare
    table_name text;
    id_sequence text;
begin
    foreach table_name in array array[
        'scans',
        'impact_actions'
    ] loop
        id_sequence := pg_get_serial_sequence(
            format('public.%I', table_name),
            'id'
        );
        if id_sequence is not null then
            execute format(
                'grant usage, select on sequence %s to anon, authenticated',
                id_sequence
            );
        end if;
    end loop;
end
$$;

notify pgrst, 'reload schema';
