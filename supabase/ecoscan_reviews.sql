create table if not exists public.ecoscan_reviews (
    id bigint generated by default as identity primary key,
    display_name text,
    rating smallint not null check (rating between 1 and 5),
    review_text text not null check (
        char_length(trim(review_text)) between 1 and 1200
    ),
    created_at timestamptz not null default now(),
    constraint ecoscan_reviews_display_name_length check (
        display_name is null
        or char_length(trim(display_name)) between 1 and 60
    )
);

alter table public.ecoscan_reviews
    drop constraint if exists ecoscan_reviews_review_text_check;

alter table public.ecoscan_reviews
    add constraint ecoscan_reviews_review_text_check
    check (char_length(trim(review_text)) between 1 and 1200);

alter table public.ecoscan_reviews enable row level security;

grant select, insert on public.ecoscan_reviews to anon, authenticated;
grant usage, select on sequence public.ecoscan_reviews_id_seq to anon, authenticated;

drop policy if exists "Anyone can read EcoScan reviews"
    on public.ecoscan_reviews;
create policy "Anyone can read EcoScan reviews"
    on public.ecoscan_reviews
    for select
    to anon, authenticated
    using (true);

drop policy if exists "Anyone can publish EcoScan reviews"
    on public.ecoscan_reviews;
create policy "Anyone can publish EcoScan reviews"
    on public.ecoscan_reviews
    for insert
    to anon, authenticated
    with check (
        rating between 1 and 5
        and char_length(trim(review_text)) between 1 and 1200
        and (
            display_name is null
            or char_length(trim(display_name)) between 1 and 60
        )
    );

drop policy if exists "Only EcoScan owner can delete reviews"
    on public.ecoscan_reviews;
revoke delete on public.ecoscan_reviews from anon, authenticated;

do $$
begin
    if not exists (
        select 1
        from pg_publication_tables
        where pubname = 'supabase_realtime'
          and schemaname = 'public'
          and tablename = 'ecoscan_reviews'
    ) then
        alter publication supabase_realtime
            add table public.ecoscan_reviews;
    end if;
end
$$;

notify pgrst, 'reload schema';
