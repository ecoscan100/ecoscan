create table if not exists public.scans (
    id bigint generated by default as identity primary key,
    created_at timestamptz not null default now()
);

alter table public.scans
    add column if not exists waste_name text,
    add column if not exists category text,
    add column if not exists disposal_method text,
    add column if not exists co2_saved numeric not null default 0;

alter table public.scans enable row level security;

grant select, insert on public.scans to anon, authenticated;

do $$
declare
    id_sequence text;
begin
    id_sequence := pg_get_serial_sequence('public.scans', 'id');
    if id_sequence is not null then
        execute format(
            'grant usage, select on sequence %s to anon, authenticated',
            id_sequence
        );
    end if;
end
$$;

drop policy if exists "Anyone can read EcoScan scans"
    on public.scans;
create policy "Anyone can read EcoScan scans"
    on public.scans
    for select
    to anon, authenticated
    using (true);

drop policy if exists "Anyone can save EcoScan scans"
    on public.scans;
create policy "Anyone can save EcoScan scans"
    on public.scans
    for insert
    to anon, authenticated
    with check (
        waste_name is not null
        and char_length(trim(waste_name)) between 1 and 120
        and category is not null
        and char_length(trim(category)) between 1 and 80
        and disposal_method is not null
        and char_length(trim(disposal_method)) between 1 and 160
        and co2_saved >= 0
    );

notify pgrst, 'reload schema';
